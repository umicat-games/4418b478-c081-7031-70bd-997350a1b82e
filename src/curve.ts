/**
 * 难度：一条按时间读的曲线，不是一张波次表。
 *
 * 一张表是一串离散的问题，有最后一行；这个游戏的难度是**任意时刻都能读出
 * 一个值**的东西。曲线的好处是可以在不玩到那儿的情况下问「第八分钟是什么
 * 样」，而且调一个常数就能改整条形状 —— 一张四十行的表只能一行一行改，还
 * 得祈祷行与行之间的走势是你想要的。
 *
 * 吸血鬼幸存者用的是一分钟一波的表。我们一局 15 分钟（它最短的图也是 15），
 * 节奏要密一倍，所以用曲线。
 */

/** 一局多长（秒）。 */
export const RUN_SECONDS = 15 * 60;

/** 两批之间隔多久。
 *
 *  指数下降而不是线性：这个类型的压力是**同时在场多少只**，等于生成速率乘上
 *  每只活多久。线性曲线的前几分钟几乎不动，然后突然掉下悬崖；指数曲线从第一
 *  分钟起每半分钟都明显更忙，到后段自然收敛在屏幕塞得下的那个密度上。
 *
 *  下限 0.22 秒不是性能限制（实测 400 只实例化后是 8 次绘制），是**可读性**：
 *  比这更密的时候，「从哪个缝里穿过去」已经看不出来了，而看不出来的局面不是
 *  更难，是另一个更糟的游戏。 */
export const spawnGapAt = (t: number): number =>
  0.22 + (1.0 - 0.22) * Math.exp(-t / 210);

/** 一批几只。
 *
 *  和间隔一起决定速率，但它们不是一回事：同样的每秒五只，「一次五只」是一堵
 *  推过来的墙，「五次一只」是持续的渗入。前者要你整体改变路线，后者要你一直
 *  微调 —— 一局里两种都要有，所以批量也爬，但爬得比频率慢。 */
export const batchAt = (t: number): number =>
  Math.round(3 + (t / RUN_SECONDS) * 5);

/** 一只敌人多少血。
 *
 *  线性，而且**慢**。血量是最没意思的一条轴 —— 更硬的敌人只是同一个问题拖得
 *  更久。它涨到刚好让开局的武器在后段不够用，仅此而已；真正让第十二分钟难的
 *  是上面那两条（密度），不是这条。 */
export const hpAt = (t: number): number => 24 + t * 0.42;

/** 玩家等级对敌人血量的加成。
 *
 *  **这是抄来的，而且是这条曲线里最聪明的一条。** 吸血鬼幸存者的敌人血量按
 *  玩家等级缩放（生成时结算），不只按时间。它是一条自平衡：升得快的人遇到的
 *  敌人也更硬，于是「构筑起飞了」和「挑战还跟得上」自动对齐，不需要为不同的
 *  成长速度各调一条曲线。
 *
 *  每级 +6%，温和 —— 它是用来防止构筑跑得太远，不是用来惩罚升级的。 */
export const hpLevelScale = (level: number): number => 1 + (level - 1) * 0.06;

/** 敌人走多快。
 *
 *  **刻意低于玩家的 4.6**：追得上玩家的敌人会让「跑」这个唯一的防御动作失效，
 *  而这个类型的全部深度在走位。它只是逐渐收窄逃生的余量。
 *
 *  这个数调过三次，中间那次的错法值得记：曲线本身封顶在 4.2，看着是安全的，
 *  但 `Swarm.spawn` 会再乘一个 **0.78~1.28** 的随机系数 —— 于是后段真实速度
 *  上界是 4.2 × 1.28 = **5.4，比玩家还快**。封顶封在乘随机之前，等于没封。
 *  （开局也一样：3.3 × 1.28 = 4.22，第一分钟就有敌人几乎追得上你。）
 *
 *  现在两头一起收：曲线 2.2 → 3.1，随机系数收窄到 0.82~1.12，而且
 *  `Swarm.spawn` 里有一道**对着玩家速度的硬上限**兜底。最快的敌人是
 *  3.1 × 1.12 = 3.47，玩家 4.6。
 *
 *  **慢下来不等于变简单。** 同一次反馈里「敌人太快」和「玩家太强」是一起来的，
 *  它们不矛盾：跑得慢的敌人更像一堵要绕开的墙，而不是一群咬着你的狗；压力
 *  该来自**密度**和**贴上来之后的代价**（见 `main.ts` 的 `CONTACT_DPS`），
 *  不是来自速度。速度只决定「跑还是不跑」这个选择成不成立。 */
export const speedAt = (t: number): number =>
  Math.min(3.1, 2.2 + t * 0.0010);

/** 第几分钟来一只精英。
 *
 *  精英是**有血条的那种**（杂兵没有 —— 几百条血条是噪音）。它存在的意义不是
 *  更硬，是打断节奏：一个必须处理掉的目标，逼你在「继续绕圈」和「停下来把它
 *  磨掉」之间选一次。 */
export const ELITE_EVERY = 75;
export const eliteHp = (n: number): number => 420 + (n - 1) * 320;
